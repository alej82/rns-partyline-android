#!/usr/bin/env python3
"""Generates logo/presplash.jpg with the app version under the badge.

The presplash is the static image python-for-android shows while Python starts,
so it cannot read APP_VERSION at runtime: the version is stamped at build time.
build-apk.sh runs this script before buildozer, right after it reads the version
from buildozer.spec, so the splash can never drift from the release.

The badge comes from app/assets/logo.png (generated by make-brand-assets.sh), so
re-running this script is idempotent: it never stamps twice.

Usage: scripts/make-presplash.py [--version X.Y.Z]
"""

import argparse
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SPEC = os.path.join(ROOT, "buildozer.spec")
BADGE = os.path.join(ROOT, "app", "assets", "logo.png")
OUT = os.path.join(ROOT, "logo", "presplash.jpg")
FONT_REGULAR = os.path.join(ROOT, "app", "assets", "RobotoEmoji.ttf")
FONT_BOLD = os.path.join(ROOT, "app", "assets", "RobotoEmoji-Bold.ttf")

WIDTH, HEIGHT = 1080, 1920
BACKGROUND = "#12141A"
BADGE_SIZE = 640
BADGE_CENTER_Y = 880
NAME_SIZE = 68
VERSION_SIZE = 44
NAME_COLOR = (236, 240, 246, 255)
VERSION_COLOR = (170, 180, 194, 255)


def buildozer_version():
    with open(SPEC, encoding="utf-8") as spec:
        for line in spec:
            match = re.match(r"\s*version\s*=\s*(\S+)", line)
            if match:
                return match.group(1)
    raise SystemExit(f"error: no version in {SPEC}")


def main():
    try:
        from PIL import Image, ImageDraw, ImageFont
    except ImportError as error:
        raise SystemExit(f"error: {error} (instala Pillow en .build-venv con scripts/setup-toolchain.sh)")

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--version", help="defaults to buildozer.spec version")
    args = parser.parse_args()
    version = args.version or buildozer_version()

    canvas = Image.new("RGB", (WIDTH, HEIGHT), BACKGROUND)

    badge = Image.open(BADGE).convert("RGBA").resize((BADGE_SIZE, BADGE_SIZE), Image.Resampling.LANCZOS)
    canvas.paste(badge, ((WIDTH - BADGE_SIZE) // 2, BADGE_CENTER_Y - BADGE_SIZE // 2), badge)

    draw = ImageDraw.Draw(canvas)
    name_font = ImageFont.truetype(FONT_BOLD, NAME_SIZE)
    version_font = ImageFont.truetype(FONT_REGULAR, VERSION_SIZE)
    draw.text(
        (WIDTH // 2, BADGE_CENTER_Y + BADGE_SIZE // 2 + 70),
        "PartyDroid",
        font=name_font,
        fill=NAME_COLOR,
        anchor="mm",
    )
    draw.text(
        (WIDTH // 2, BADGE_CENTER_Y + BADGE_SIZE // 2 + 140),
        f"v{version}",
        font=version_font,
        fill=VERSION_COLOR,
        anchor="mm",
    )

    canvas.save(OUT, "JPEG", quality=90)
    print(f"Wrote {os.path.relpath(OUT, ROOT)} (v{version})")


if __name__ == "__main__":
    main()
